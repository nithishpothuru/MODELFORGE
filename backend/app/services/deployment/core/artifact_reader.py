    @classmethod
    def read_from_file(cls, file_path: Union[str, Path], working_directory_override: Optional[str] = None) -> DeploymentRequest:
        p = Path(file_path).resolve()
        if not p.exists():
            raise ArtifactValidationError(f"Artifact file or directory not found: {p}")

        if p.is_dir():
            reader = cls(base_upload_dir=p.parent)
            artifact = reader.resolve_artifact(artifact_path=p)
            return cls.to_deployment_request(artifact)

        try:
            content = p.read_text(encoding="utf-8")
            data = json.loads(content)
        except Exception as exc:
            raise ArtifactValidationError(f"Failed to parse artifact JSON from {p}: {exc}") from exc

        if "working_directory" not in data and "extracted_path" not in data:
            data["working_directory"] = str(p.parent)

        if working_directory_override:
            data["working_directory"] = working_directory_override

        return cls.read_from_dict(data)

    @classmethod
    def read_from_json(cls, json_str: str) -> DeploymentRequest:
        try:
            data = json.loads(json_str)
        except Exception as exc:
            raise ArtifactValidationError(f"Malformed artifact JSON string: {exc}") from exc

        return cls.read_from_dict(data)

    @classmethod
    def read_from_dict(cls, data: Dict[str, Any]) -> DeploymentRequest:
        if not isinstance(data, dict):
            raise ArtifactValidationError("Artifact data must be a dictionary.")

        project_id = data.get("project_id") or data.get("id")
        if not project_id:
            raise ArtifactValidationError("Artifact missing required 'project_id'.")

        status_val = str(data.get("status", "")).lower()
        project_status_val = str(data.get("project_status", "")).lower()
        explicit_ready = data.get("deployment_ready")

        if explicit_ready is False:
            raise ArtifactValidationError(f"Project {project_id} is marked as not deployment ready.")

        if status_val in ("failed", "validation_failed") or project_status_val in ("failed", "validation_failed"):
            raise ArtifactValidationError(f"Project {project_id} validation status is '{status_val or project_status_val}'; cannot deploy.")

        val_rep = data.get("validation_report") or {}
        if not isinstance(val_rep, dict):
            val_rep = {}

        working_dir = (
            data.get("working_directory")
            or data.get("extracted_path")
            or data.get("workspace_path")
            or data.get("extract_dir")
            or data.get("project_path")
            or val_rep.get("project_path")
            or val_rep.get("working_directory")
            or val_rep.get("extracted_path")
        )
        if not working_dir:
            raise ArtifactValidationError("Artifact missing 'working_directory' or 'extracted_path'.")

        work_path = Path(working_dir).resolve()
        if not work_path.exists() or not work_path.is_dir():
            raise ArtifactValidationError(f"Working directory does not exist: {work_path}")

        reader = cls(base_upload_dir=work_path.parent)
        norm_root, detected_ep = reader._detect_real_project_root(work_path, val_rep or data)
        work_path = norm_root

        framework = data.get("framework") or val_rep.get("framework")
        if not framework:
            structure = data.get("structure") or val_rep.get("structure") or {}
            detected_fws = structure.get("detected_frameworks") or []
            if detected_fws:
                framework = detected_fws[0]
            else:
                ep_val = data.get("entry_point_validation") or val_rep.get("entry_point_validation") or {}
                ep_type = ep_val.get("entry_point_type")
                if ep_type in ("fastapi", "flask", "streamlit"):
                    framework = ep_type
                elif ep_type in ("cli_script", "inference_function"):
                    framework = "cli"
                else:
                    framework = "fastapi"
        framework = str(framework).lower().strip()

        python_ver = data.get("python_version") or val_rep.get("python_version")
        if isinstance(python_ver, dict):
            python_ver = python_ver.get("version", "3.11")
        elif not python_ver:
            python_ver = "3.11"
        python_ver = str(python_ver).strip()
        if python_ver.count(".") >= 2:
            python_ver = ".".join(python_ver.split(".")[:2])

        ep_val = data.get("entry_point_validation") or val_rep.get("entry_point_validation") or {}
        entry_point = (
            data.get("entry_point")
            or data.get("main_file")
            or val_rep.get("entry_point")
            or val_rep.get("main_file")
            or ep_val.get("detected_entry_point")
            or detected_ep
        )
        if isinstance(entry_point, dict):
            entry_point = entry_point.get("file") or entry_point.get("path")
        if not entry_point:
            entry_point = "main.py"

        req_file = (
            data.get("requirements_file")
            or val_rep.get("requirements_file")
            or val_rep.get("requirements")
        )
        if isinstance(req_file, dict):
            req_file = req_file.get("file") or req_file.get("path")
        if not req_file:
            dep_res = data.get("dependency_resolution") or val_rep.get("dependency_resolution") or {}
            if dep_res.get("lock_file_generated") and dep_res.get("lock_file_path"):
                req_file = dep_res.get("lock_file_path")
            elif (work_path / "requirements-resolved.txt").exists():
                req_file = "requirements-resolved.txt"
            else:
                req_file = "requirements.txt"

        req_file_name = Path(str(req_file)).name if req_file else "requirements.txt"

        project_name = data.get("project_name") or data.get("title") or f"Project-{project_id[:8]}"
        deployment_id = data.get("deployment_id")
        target_port = data.get("target_port")
        if not target_port:
            if framework == "flask":
                target_port = 5000
            elif framework == "streamlit":
                target_port = 8501
            elif framework == "cli":
                target_port = 8000
            else:
                target_port = 8000

        health_endpoint = data.get("health_endpoint")
        if not health_endpoint:
            health_endpoint = "/_stcore/health" if framework == "streamlit" else "/health"

        req_kwargs: Dict[str, Any] = {
            "project_id": str(project_id),
            "project_name": str(project_name),
            "framework": framework,
            "python_version": python_ver,
            "entry_point": str(entry_point),
            "requirements_file": req_file_name,
            "working_directory": str(work_path),
            "deployment_ready": True,
            "target_port": int(target_port),
            "health_endpoint": str(health_endpoint),
            "env_vars": data.get("env_vars", {}),
            "memory_limit": data.get("memory_limit"),
            "cpu_limit": data.get("cpu_limit"),
            "enable_nginx": data.get("enable_nginx", True),
            "domain_name": data.get("domain_name"),
            "labels": data.get("labels", {}),
        }

        # Resolve entry_point_type and startup_command
        raw_ep_type = (
            data.get("entry_point_type") or 
            val_rep.get("entry_point_type") or 
            ep_val.get("entry_point_type") or 
            data.get("entry_type")
        )
        resolved_ep_type, resolved_startup_cmd = cls.select_startup_command(
            entry_point_type=raw_ep_type,
            entry_point=str(entry_point),
            port=int(target_port),
            framework=framework
        )
        req_kwargs["entry_point_type"] = resolved_ep_type
        req_kwargs["startup_command"] = data.get("startup_command") or resolved_startup_cmd

        if deployment_id:
            req_kwargs["deployment_id"] = str(deployment_id)
        if "host_port" in data and data["host_port"] is not None:
            req_kwargs["host_port"] = int(data["host_port"])
        if "port" in data and data["port"] is not None:
            req_kwargs["host_port"] = int(data["port"])

        return DeploymentRequest(**req_kwargs)

    @classmethod
    def to_deployment_artifact(cls, source: Union[DeploymentRequest, Dict[str, Any], Path, str]) -> DeploymentArtifact:
        if isinstance(source, DeploymentArtifact):
            return source

        if isinstance(source, DeploymentRequest):
            work_p = Path(source.working_directory).resolve()
            ep = source.entry_point
            ep_p = work_p / ep if (work_p / ep).exists() else None
            df_p = work_p / "Dockerfile"
            resolved_ep_type, resolved_startup_cmd = cls.select_startup_command(
                entry_point_type=source.entry_point_type,
                entry_point=ep,
                port=source.target_port,
                framework=source.framework
            )
            return DeploymentArtifact(
                project_id=source.project_id or "unassigned",
                project_name=source.project_name or "ModelForge Project",
                project_root=work_p,
                entry_point=ep,
                entry_point_path=ep_p,
                entry_point_type=source.entry_point_type or resolved_ep_type,
                startup_command=source.startup_command or resolved_startup_cmd,
                framework=source.framework,
                python_version=source.python_version,
                dependencies=[],
                requirements_file=source.requirements_file or "requirements.txt",
                has_dockerfile=df_p.exists(),
                dockerfile_path=df_p if df_p.exists() else None,
                metadata={"deployment_id": source.deployment_id}
            )

        reader = cls()
        if isinstance(source, dict):
            return reader.resolve_artifact(artifact_dict=source)
        elif isinstance(source, (Path, str)):
            p = Path(str(source))
            if p.exists():
                return reader.resolve_artifact(artifact_path=p)
            return reader.resolve_artifact(project_id=str(source))

        raise ArtifactValidationError(f"Cannot convert type '{type(source)}' to DeploymentArtifact")

    @staticmethod
    def to_deployment_request(artifact: DeploymentArtifact) -> DeploymentRequest:
        target_port = 8000
        if artifact.framework == "flask":
            target_port = 5000
        elif artifact.framework == "streamlit":
            target_port = 8501

        return DeploymentRequest(
            project_id=artifact.project_id,
            project_name=artifact.project_name,
            framework=artifact.framework,
            python_version=artifact.python_version,
            entry_point=artifact.entry_point,
            entry_point_type=artifact.entry_point_type,
            startup_command=artifact.startup_command,
            requirements_file=artifact.requirements_file,
            working_directory=str(artifact.project_root),
            target_port=target_port,
            deployment_ready=True
        )

"""
Artifact Reader
Consumes validated deployment artifacts / validation reports from the CI validation pipeline.
Detects real project roots, normalizes nested folders, locates entry points and resolved requirements,
and constructs clean DeploymentArtifact (and DeploymentRequest) objects.
"""

import json
import shutil
import logging
from pathlib import Path
from typing import Dict, Any, Union, Optional, List, Tuple

from ..models.deployment_request import DeploymentRequest
from ..models.deployment_artifact import DeploymentArtifact

logger = logging.getLogger("deployment.artifact_reader")


class ArtifactValidationError(ValueError):
    """Raised when deployment artifact is missing required fields or indicates unvalidated project."""
    pass


class ArtifactReader:
    """
    Reads deployment artifacts generated by the validation pipeline.
    Validates deployment prerequisites and constructs DeploymentArtifact objects.
    """

    ENTRY_POINT_CANDIDATES = [
        "main.py", "app.py", "serve.py", "server.py", 
        "api.py", "predict.py", "inference.py", "run.py", "wsgi.py"
    ]
    
    FRAMEWORK_SIGNATURES = {
        "fastapi": ["fastapi", "uvicorn"],
        "streamlit": ["streamlit"],
        "flask": ["flask", "gunicorn", "werkzeug"],
        "torch": ["torch", "torchvision"],
        "tensorflow": ["tensorflow", "keras"],
        "sklearn": ["scikit-learn", "sklearn"]
    }

    REQUIRED_FIELDS = ["project_id"]

    def __init__(self, base_upload_dir: Optional[Union[str, Path]] = None):
        if base_upload_dir:
            self.base_upload_dir = Path(base_upload_dir).resolve()
        else:
            current_file = Path(__file__).resolve()
            candidate_backend = current_file.parent.parent.parent.parent.parent / "uploads"
            candidate_local = Path("./backend/uploads").resolve()
            candidate_cur = Path("./uploads").resolve()
            if candidate_backend.exists():
                self.base_upload_dir = candidate_backend
            elif candidate_local.exists():
                self.base_upload_dir = candidate_local
            else:
                self.base_upload_dir = candidate_cur

    def resolve_artifact(self,
                         project_id: Optional[str] = None,
                         validation_id: Optional[str] = None,
                         artifact_path: Optional[Union[str, Path]] = None,
                         artifact_dict: Optional[Dict[str, Any]] = None) -> DeploymentArtifact:
        """
        Locate and build a DeploymentArtifact from project_id, validation_id, artifact_path, or dict.
        Normalizes nested extracted directories automatically.
        """
        target_id = project_id or validation_id
        logger.info("[Artifact Loading] Resolving artifact (target_id='%s', path='%s')", target_id, artifact_path)

        search_dir: Optional[Path] = None
        report_data: Dict[str, Any] = {}

        # 1. Direct artifact dictionary
        if artifact_dict and isinstance(artifact_dict, dict):
            if not target_id:
                target_id = artifact_dict.get("project_id") or artifact_dict.get("id")
            
            nested_report = artifact_dict.get("validation_report")
            if isinstance(nested_report, dict):
                report_data = {**artifact_dict, **nested_report}
                if "status" in artifact_dict:
                    report_data["status"] = artifact_dict["status"]
                if "project_status" in artifact_dict:
                    report_data["project_status"] = artifact_dict["project_status"]
            else:
                report_data = dict(artifact_dict)

            raw_work_dir = (
                artifact_dict.get("working_directory") or 
                artifact_dict.get("extracted_path") or 
                artifact_dict.get("project_path") or
                report_data.get("working_directory") or
                report_data.get("project_path")
            )
            if raw_work_dir:
                search_dir = Path(raw_work_dir).resolve()

        # 2. From file or directory path
        if not search_dir and artifact_path:
            p = Path(artifact_path).resolve()
            if p.is_file():
                if p.suffix.lower() == ".json":
                    try:
                        content = p.read_text(encoding="utf-8")
                        loaded = json.loads(content)
                        nested_rep = loaded.get("validation_report")
                        if isinstance(nested_rep, dict):
                            report_data = {**loaded, **nested_rep}
                            if "status" in loaded:
                                report_data["status"] = loaded["status"]
                        else:
                            report_data = loaded
                        if not target_id:
                            target_id = loaded.get("project_id") or loaded.get("id")
                        raw_dir = loaded.get("working_directory") or loaded.get("extracted_path")
                        search_dir = Path(raw_dir).resolve() if raw_dir else p.parent
                    except Exception as e:
                        logger.warning("[Artifact Loading] Error parsing JSON at %s: %s", p, e)
                        search_dir = p.parent
                else:
                    search_dir = p.parent
            elif p.is_dir():
                search_dir = p

        # 3. Locate from project_id or validation_id in uploads
        if not search_dir and target_id:
            search_dir = self._find_project_dir_by_id(target_id)

        # 4. Fallback search: look inside base_upload_dir
        if not search_dir or not search_dir.exists():
            if target_id and self.base_upload_dir.exists():
                for folder in self.base_upload_dir.iterdir():
                    if folder.is_dir() and target_id in folder.name:
                        search_dir = folder
                        break

        # Check validation readiness before proceeding
        self._check_validation_readiness(target_id, report_data)

        if not search_dir or not search_dir.exists():
            raise ArtifactValidationError(
                f"Artifact directory not found for project '{target_id or artifact_path}'. "
                f"Searched within '{self.base_upload_dir}'."
            )

        logger.info("[Artifact Loading] Located search directory: %s", search_dir)

        # 5. Find and load validation_report.json if not yet loaded
        if not report_data or not isinstance(report_data, dict) or "status" not in report_data:
            found_report = self._find_validation_report(search_dir)
            if found_report:
                report_data = found_report

        # 6. Validate project readiness / CI status
        self._check_validation_readiness(target_id, report_data)
        target_id = target_id or report_data.get("project_id") or report_data.get("id")

        # 7. Detect real project root (normalizes nested directories)
        project_root, detected_ep_name = self._detect_real_project_root(search_dir, report_data)
        logger.info("[Artifact Loading] Normalized project root: %s", project_root)

        # 8. Locate requirements file (requirements-resolved.txt preferred, else requirements.txt)
        req_file_name, dependencies = self._resolve_requirements(search_dir, project_root, report_data)

        # 9. Detect entry point
        entry_point, entry_point_path = self._resolve_entry_point(project_root, detected_ep_name, report_data)

        # 10. Detect framework & Python version
        framework = self._detect_framework(dependencies, report_data, project_root)
        python_version = self._detect_python_version(report_data)

        # 11. Check for existing Dockerfile
        dockerfile = project_root / "Dockerfile"
        has_dockerfile = dockerfile.exists() and dockerfile.is_file()

        project_name = (
            report_data.get("project_name") or 
            report_data.get("title") or 
            (target_id and f"Project-{target_id[:8]}") or 
            project_root.name
        )

        # 12. Detect entry_point_type and select dynamic startup command
        ep_val = report_data.get("entry_point_validation") or {}
        raw_ep_type = (
            report_data.get("entry_point_type") or
            ep_val.get("entry_point_type") or
            report_data.get("entry_type")
        )
        if artifact_dict and isinstance(artifact_dict, dict) and "entry_point_type" in artifact_dict:
            raw_ep_type = artifact_dict["entry_point_type"]

        entry_point_type, startup_cmd = self.select_startup_command(
            entry_point_type=raw_ep_type,
            entry_point=entry_point,
            port=5000 if framework == "flask" else 8000,
            framework=framework
        )

        return DeploymentArtifact(
            project_id=str(target_id or project_root.name),
            project_name=str(project_name),
            project_root=project_root,
            entry_point=entry_point,
            entry_point_path=entry_point_path,
            entry_point_type=entry_point_type,
            startup_command=startup_cmd,
            framework=framework,
            python_version=python_version,
            dependencies=dependencies,
            requirements_file=req_file_name,
            has_dockerfile=has_dockerfile,
            dockerfile_path=dockerfile if has_dockerfile else None,
            validation_report=report_data,
            metadata={
                "search_dir": str(search_dir),
                "is_nested_normalized": (project_root != search_dir),
                "entry_point_type": entry_point_type,
                "startup_command": startup_cmd,
            }
        )

    def _find_project_dir_by_id(self, target_id: str) -> Optional[Path]:
        """Check known upload paths and Supabase Storage for project_id or validation_id."""
        candidate_roots = [
            self.base_upload_dir,
            Path("./uploads").resolve(),
            Path("./backend/uploads").resolve(),
            Path(__file__).resolve().parent.parent.parent.parent.parent / "uploads"
        ]
        for candidate_root in candidate_roots:
            if not candidate_root.exists():
                continue
            cand = candidate_root / target_id
            if cand.exists() and cand.is_dir():
                return cand.resolve()
            for report_file in candidate_root.rglob("validation_report.json"):
                try:
                    data = json.loads(report_file.read_text(encoding="utf-8"))
                    if data.get("id") == target_id or data.get("project_id") == target_id:
                        return report_file.parent.resolve()
                except Exception:
                    continue

        # Fallback: Check Supabase Storage if not present locally
        try:
            from app.services.storage_service import storage_service
            dest_dir = self.base_upload_dir / target_id / "extracted"
            downloaded = storage_service.download_directory_from_supabase(target_id, dest_dir)
            if downloaded:
                logger.info("[Artifact Loading] Downloaded %d artifacts from Supabase Storage for %s", len(downloaded), target_id)
                return (self.base_upload_dir / target_id).resolve()
        except Exception as exc:
            logger.debug("Non-fatal Supabase storage download check: %s", exc)

        return None

    def _find_validation_report(self, search_dir: Path) -> Optional[Dict[str, Any]]:
        """Look for validation_report.json inside search_dir or extracted/."""
        candidates = [
            search_dir / "validation_report.json",
            search_dir / "extracted" / "validation_report.json"
        ]
        for c in candidates:
            if c.exists() and c.is_file():
                try:
                    return json.loads(c.read_text(encoding="utf-8"))
                except Exception as e:
                    logger.warning("[Artifact Loading] Error reading %s: %s", c, e)

        for c in search_dir.rglob("validation_report.json"):
            try:
                return json.loads(c.read_text(encoding="utf-8"))
            except Exception:
                continue

        return None

    def _check_validation_readiness(self, target_id: Optional[str], report_data: Dict[str, Any]) -> None:
        """Verify the artifact has passed validation."""
        if not report_data:
            return

        status_val = str(report_data.get("status", "")).lower()
        project_status_val = str(report_data.get("project_status", "")).lower()
        explicit_ready = report_data.get("deployment_ready")

        if explicit_ready is False:
            raise ArtifactValidationError(
                f"Project '{target_id}' is marked as not deployment ready."
            )

        if status_val in ("failed", "validation_failed") or project_status_val in ("failed", "validation_failed"):
            raise ArtifactValidationError(
                f"Project '{target_id}' validation status is '{status_val or project_status_val}'; cannot deploy."
            )

    def _detect_real_project_root(self, search_dir: Path, report_data: Dict[str, Any]) -> Tuple[Path, Optional[str]]:
        """
        Detects the real project root directory, automatically normalizing nested wrappers:
        uploads/<project_id>/extracted/Sample_ML_Project/Sample_ML_Project
        Returns (project_root, detected_entry_point_name).
        """
        extracted_dir = search_dir / "extracted"
        start_dir = extracted_dir if (extracted_dir.exists() and extracted_dir.is_dir()) else search_dir

        ep_val = report_data.get("entry_point_validation") or {}
        reported_ep = ep_val.get("detected_entry_point") or report_data.get("main_file") or report_data.get("entry_point")
        if isinstance(reported_ep, dict):
            reported_ep = reported_ep.get("file") or reported_ep.get("path")

        if reported_ep:
            reported_str = str(reported_ep).replace("\\", "/")
            candidate_file = start_dir / reported_str
            if candidate_file.exists() and candidate_file.is_file():
                return candidate_file.parent, candidate_file.name

            ep_filename = Path(reported_str).name
            matches = list(start_dir.rglob(ep_filename))
            if matches:
                return matches[0].parent, matches[0].name

        for ep_name in self.ENTRY_POINT_CANDIDATES:
            matches = [m for m in start_dir.rglob(ep_name) if not any(part.startswith(".") or part in ("venv", "env", "__pycache__") for part in m.parts)]
            if matches:
                for m in matches:
                    if (m.parent / "requirements.txt").exists() or (m.parent / "requirements-resolved.txt").exists():
                        return m.parent, m.name
                return matches[0].parent, matches[0].name

        current = start_dir
        markers = ["requirements.txt", "requirements-resolved.txt", "setup.py", "pyproject.toml"]
        while True:
            subdirs = [p for p in current.iterdir() if p.is_dir() and not p.name.startswith(".") and p.name not in ("venv", "env", "__pycache__")]
            if any((current / m).exists() for m in markers) or list(current.glob("*.py")):
                return current, None
            if len(subdirs) == 1:
                current = subdirs[0]
            else:
                break

        py_files = list(start_dir.rglob("*.py"))
        if py_files:
            return py_files[0].parent, py_files[0].name

        return current, None

    def _resolve_requirements(self, search_dir: Path, project_root: Path, report_data: Dict[str, Any]) -> Tuple[str, List[str]]:
        resolved_candidates = [
            project_root / "requirements-resolved.txt",
            search_dir / "extracted" / "requirements-resolved.txt",
            search_dir / "requirements-resolved.txt"
        ]
        
        chosen_req_file = "requirements.txt"
        req_path: Optional[Path] = None

        for cand in resolved_candidates:
            if cand.exists() and cand.is_file():
                req_path = cand
                chosen_req_file = "requirements-resolved.txt"
                target_in_root = project_root / "requirements-resolved.txt"
                if cand != target_in_root:
                    try:
                        shutil.copy2(cand, target_in_root)
                        logger.info("[Artifact Loading] Synced requirements-resolved.txt into project root: %s", target_in_root)
                    except Exception as e:
                        logger.warning("[Artifact Loading] Could not copy requirements-resolved.txt: %s", e)
                break

        if not req_path:
            standard_candidates = [
                project_root / "requirements.txt",
                search_dir / "extracted" / "requirements.txt",
                search_dir / "requirements.txt"
            ]
            for cand in standard_candidates:
                if cand.exists() and cand.is_file():
                    req_path = cand
                    chosen_req_file = "requirements.txt"
                    target_in_root = project_root / "requirements.txt"
                    if cand != target_in_root:
                        try:
                            shutil.copy2(cand, target_in_root)
                            logger.info("[Artifact Loading] Synced requirements.txt into project root: %s", target_in_root)
                        except Exception:
                            pass
                    break

        dependencies: List[str] = []
        if req_path and req_path.exists():
            try:
                lines = req_path.read_text(encoding="utf-8").splitlines()
                dependencies = [line.strip() for line in lines if line.strip() and not line.strip().startswith("#")]
            except Exception as e:
                logger.warning("[Artifact Loading] Error reading requirements file %s: %s", req_path, e)

        if not dependencies:
            dep_res = report_data.get("dependency_resolution") or {}
            resolved_pkgs = dep_res.get("resolved_packages") or []
            for pkg in resolved_pkgs:
                if isinstance(pkg, dict) and "name" in pkg:
                    ver = pkg.get("version")
                    dependencies.append(f"{pkg['name']}=={ver}" if ver else pkg["name"])

        return chosen_req_file, dependencies

    def _resolve_entry_point(self, project_root: Path, detected_ep_name: Optional[str], report_data: Dict[str, Any]) -> Tuple[str, Path]:
        if detected_ep_name:
            candidate = project_root / detected_ep_name
            if candidate.exists() and candidate.is_file():
                return detected_ep_name, candidate

        for ep in self.ENTRY_POINT_CANDIDATES:
            candidate = project_root / ep
            if candidate.exists() and candidate.is_file():
                return ep, candidate

        for ep in self.ENTRY_POINT_CANDIDATES:
            matches = list(project_root.rglob(ep))
            if matches:
                rel = str(matches[0].relative_to(project_root)).replace("\\", "/")
                return rel, matches[0]

        fallback = project_root / "main.py"
        return "main.py", fallback

    def _detect_framework(self, dependencies: List[str], report_data: Dict[str, Any], project_root: Path) -> str:
        if report_data.get("framework"):
            return str(report_data["framework"]).lower().strip()

        structure = report_data.get("structure") or {}
        detected_fws = structure.get("detected_frameworks") or []
        if detected_fws:
            return str(detected_fws[0]).lower().strip()

        ep_val = report_data.get("entry_point_validation") or {}
        ep_type = ep_val.get("entry_point_type")
        if ep_type in ("fastapi", "flask", "streamlit"):
            return ep_type
        elif ep_type in ("cli_script", "inference_function"):
            return "cli"

        dep_str = " ".join(dependencies).lower()
        for fw, sigs in self.FRAMEWORK_SIGNATURES.items():
            if any(s in dep_str for s in sigs):
                return fw

        for py_file in project_root.glob("*.py"):
            try:
                content = py_file.read_text(encoding="utf-8", errors="ignore").lower()
                for fw, sigs in self.FRAMEWORK_SIGNATURES.items():
                    if any(f"import {s}" in content or f"from {s}" in content for s in sigs):
                        return fw
            except Exception:
                continue

        # Check if entry point is a typical CLI script (predict.py, train.py, etc.)
        for py_file in project_root.glob("*.py"):
            if py_file.name in ("predict.py", "train.py", "inference.py", "cli.py"):
                return "cli"

        return "fastapi"

    @classmethod
    def select_startup_command(cls,
                               entry_point_type: Optional[str] = None,
                               entry_point: str = "main.py",
                               port: int = 8000,
                               framework: Optional[str] = None) -> Tuple[str, str]:
        """
        Dynamically determine (entry_point_type, startup_command).
        
        Rules:
        1. If entry_point_type == "fastapi"
           -> start using uvicorn.
        2. If entry_point_type == "flask"
           -> start using python app.py (or detected Flask entry).
        3. If entry_point_type == "cli_script"
           -> start using python <detected_entry_point>.
        4. Never hardcode uvicorn for every project.
        """
        ep_type = (entry_point_type or "").lower().strip()
        ep_name = Path(entry_point).name.lower()
        fw_name = (framework or "").lower().strip()

        # Rule 3 check: explicit cli_script or inferred from entry point name / framework
        if ep_type in ("cli_script", "inference_function", "cli", "python_cli", "script"):
            if ep_type == "script" and ep_name not in ("predict.py", "train.py", "inference.py") and "fastapi" in fw_name:
                ep_type = "fastapi"
            else:
                ep_type = "cli_script"
        elif ep_type == "flask":
            ep_type = "flask"
        elif ep_type == "fastapi":
            ep_type = "fastapi"
        elif ep_type == "streamlit":
            ep_type = "streamlit"
        elif not ep_type or ep_type == "unknown":
            if ep_name in ("predict.py", "train.py", "inference.py") or "cli" in fw_name:
                ep_type = "cli_script"
            elif "flask" in fw_name:
                # When framework is flask and entry_point_type is not provided,
                # keep legacy gunicorn behavior so existing tests continue to work.
                clean = entry_point.replace("\\", "/").strip()
                if ":" in clean:
                    app_module = clean
                elif clean.endswith(".py"):
                    app_module = f"{clean[:-3].replace('/', '.')}:app"
                else:
                    app_module = f"{clean}:app"
                return "flask", f"gunicorn --bind 0.0.0.0:{port} {app_module}"
            elif "streamlit" in fw_name:
                ep_type = "streamlit"
            else:
                ep_type = "fastapi"

        # Construct startup command according to rules
        if ep_type == "fastapi":
            clean = entry_point.replace("\\", "/").strip()
            if ":" in clean:
                app_module = clean
            elif clean.endswith(".py"):
                app_module = f"{clean[:-3].replace('/', '.')}:app"
            else:
                app_module = f"{clean}:app"
            cmd = f"uvicorn {app_module} --host 0.0.0.0 --port {port}"
        elif ep_type == "flask":
            cmd = f"python {entry_point}"
        elif ep_type == "cli_script":
            cmd = f"python {entry_point}"
        elif ep_type == "streamlit":
            cmd = f"streamlit run {entry_point} --server.port={port} --server.address=0.0.0.0"
        else:
            cmd = f"python {entry_point}"

        return ep_type, cmd

    def _detect_python_version(self, report_data: Dict[str, Any]) -> str:
        py_ver = report_data.get("python_version")
        if isinstance(py_ver, dict):
            py_ver = py_ver.get("version", "3.11")
        elif not py_ver:
            py_ver = "3.11"
        py_ver_str = str(py_ver).strip()
        if py_ver_str.count(".") >= 2:
            py_ver_str = ".".join(py_ver_str.split(".")[:2])
        return py_ver_str or "3.11"

